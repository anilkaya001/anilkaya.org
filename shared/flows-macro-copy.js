export function say(key, fields) {
  const t = COPY[key];
  if (typeof t !== "string") return null;
  const f = fields || {};
  return t.replace(/\{([a-z0-9]+)\}/g, (m, name) => (f[name] === undefined || f[name] === null ? m : String(f[name])));
}
